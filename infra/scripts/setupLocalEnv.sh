#!/bin/bash
# setupLocalEnv.sh — Generate .env.local.example and optionally .env.local
# Run from repository root: ./infra/scripts/setupLocalEnv.sh
#
# Creates the environment variable template with all required keys.
# Copy to .env.local and fill in real values before running services.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../" && pwd)"
ENV_EXAMPLE="$REPO_ROOT/.env.local.example"
ENV_OUTPUT="$REPO_ROOT/.env.local"

# Generate .env.local.example
{
  echo "# Vietnam Smart Golf Platform — Environment Variable Template"
  echo "# DO NOT commit this file with real values. Copy to .env.local and fill in secrets."
  echo "# Real values are injected at runtime. NEVER commit .env.local to version control."
  echo "#"
  echo "# How to use:"
  echo "#   cp .env.local.example .env.local"
  echo "#   # Edit .env.local with your values"
  echo "#"
  echo ""
  echo "# ============================================"
  echo "# Database (PostgreSQL + PostGIS via Docker)"
  echo "# ============================================"
  echo "DATABASE_HOST=localhost"
  echo "DATABASE_PORT=5432"
  echo "# Database name — matches POSTGRES_DB in docker-compose.yaml"
  echo "DATABASE_NAME=vsp"
  echo "# Database user — matches POSTGRES_USER in docker-compose.yaml"
  echo "DATABASE_USER=vsp"
  echo "# Database password — matches POSTGRES_PASSWORD in docker-compose.yaml"
  echo "# Default dev password is 'vsp_dev_password' (DO NOT use in production)"
  echo "DATABASE_PASSWORD=vsp_dev_password"
  echo ""
  echo "# ============================================"
  echo "# Redis (via Docker)"
  echo "# ============================================"
  echo "REDIS_HOST=localhost"
  echo "REDIS_PORT=6379"
  echo "# Redis password (default: no password in local dev)"
  echo "REDIS_PASSWORD="
  echo ""
  echo "# ============================================"
  echo "# API Server"
  echo "# ============================================"
  echo "API_HOST=localhost"
  echo "API_PORT=8080"
  echo "API_BASE_URL=http://localhost:8080"
  echo ""
  echo "# ============================================"
  echo "# Mobile App"
  echo "# ============================================"
  echo "MOBILE_API_BASE_URL=http://localhost:8080"
  echo ""
  echo "# ============================================"
  echo "# Authentication / Secrets"
  echo "# ============================================"
  echo "# JWT secret — generate with: openssl rand -base64 32"
  echo "JWT_SECRET="
  echo "# Session secret — generate with: openssl rand -base64 32"
  echo "SESSION_SECRET="
  echo "# Encryption key for sensitive data — generate with: openssl rand -base64 32"
  echo "ENCRYPTION_KEY="
  echo ""
  echo "# ============================================"
  echo "# Feature Flags"
  echo "# ============================================"
  echo "# ENABLE_FEATURE_X=false"
  echo ""
  echo "# ============================================"
  echo "# TLS / SSL (Production)"
  echo "# ============================================"
  echo "# Path to PKCS#12 keystore containing server certificate + private key"
  echo "# Generate with: openssl pkcs12 -export -in cert.pem -inkey key.pem -out keystore.p12"
  echo "VSP_SSL_KEYSTORE_PATH=/etc/vsp/ssl/keystore.p12"
  echo "# Keystore password — store in secrets manager, never here in production"
  echo "VSP_SSL_KEYSTORE_PASSWORD="
  echo "# Truststore path for client certificate auth"
  echo "VSP_SSL_TRUSTSTORE_PATH=/etc/vsp/ssl/truststore.p12"
  echo "# Truststore password — store in secrets manager, never here in production"
  echo "VSP_SSL_TRUSTSTORE_PASSWORD="
  echo ""
  echo "# ============================================"
  echo "# Database Encryption at Rest"
  echo "# ============================================"
  echo "# PostgreSQL pgcrypto symmetric key reference (base64-encoded 256-bit key)"
  echo "# Generate with: openssl rand -base64 32"
  echo "# In production, load from AWS KMS or HashiCorp Vault via VSP_SECRETS_MANAGER_KMS_KEY_ID"
  echo "VSP_DB_ENCRYPTION_KEY_REF=local-dev-key"
  echo ""
  echo "# ============================================"
  echo "# Secrets Manager (AWS Secrets Manager / HashiCorp Vault)"
  echo "# ============================================"
  echo "# AWS region for Secrets Manager"
  echo "VSP_SECRETS_MANAGER_REGION=ap-southeast-1"
  echo "# Secrets Manager secret name for the API service account"
  echo "VSP_SECRETS_MANAGER_SECRET_NAME=vsp/api-prod"
  echo "# AWS KMS key ID used for envelope encryption of secrets"
  echo "VSP_SECRETS_MANAGER_KMS_KEY_ID="
  echo "# Vault address (if using HashiCorp Vault instead of AWS Secrets Manager)"
  echo "VSP_SECRETS_MANAGER_VAULT_ADDR="
  echo "# Vault AppRole role ID"
  echo "VSP_SECRETS_MANAGER_VAULT_ROLE_ID="
  echo "# Vault AppRole secret ID"
  echo "VSP_SECRETS_MANAGER_VAULT_SECRET_ID="
  echo ""
  echo "# ============================================"
  echo "# Backup Retention"
  echo "# ============================================"
  echo "# Backup schedule — cron expression (UTC)"
  echo "VSP_BACKUP_SCHEDULE=daily"
  echo "# Daily incremental backup retention (days)"
  echo "VSP_BACKUP_RETENTION_DAYS=30"
  echo "# Weekly full backup retention (weeks)"
  echo "VSP_BACKUP_RETENTION_WEEKS=12"
  echo "# Monthly archive retention (months)"
  echo "VSP_BACKUP_RETENTION_MONTHS=12"
  echo "# Annual compliance archive retention (years)"
  echo "VSP_BACKUP_RETENTION_YEARS=7"
  echo "# S3 bucket for encrypted backup uploads"
  echo "VSP_BACKUP_S3_BUCKET="
  echo "# S3 prefix within the bucket"
  echo "VSP_BACKUP_S3_PREFIX=prod/backups"
  echo "# Backup encryption key ID (KMS CMK)"
  echo "VSP_BACKUP_ENCRYPTION_KEY_ID="
  echo ""
} > "$ENV_EXAMPLE"

echo "✅ Created .env.local.example at $ENV_EXAMPLE"
echo ""

# Offer to create .env.local if not already present
if [[ -f "$ENV_OUTPUT" ]]; then
  echo "⚠️  .env.local already exists — skipping auto-creation."
  echo "    Remove $ENV_OUTPUT to regenerate."
else
  cp "$ENV_EXAMPLE" "$ENV_OUTPUT"
  echo "✅ Created .env.local at $ENV_OUTPUT"
  echo ""
  echo "⚠️  IMPORTANT: Fill in real secrets in .env.local before running services."
  echo "    NEVER commit .env.local to version control."
fi
